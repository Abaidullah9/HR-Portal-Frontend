'use client'

import { useEffect, useState } from 'react'
import { Download, FileBarChart, Plus } from 'lucide-react'
import { AppLayout } from '@/components/layout/app-layout'
import { SectionHeader } from '@/components/common/section-header'
import { Badge } from '@/components/common/badge'
import { DataTable, DataTableSkeleton } from '@/components/common/data-table'
import { EmptyState } from '@/components/common/state-panel'
import { AccessDenied } from '@/components/common/access-denied'
import { Button } from '@/components/ui/button'
import { usePermissions } from '@/lib/hooks/use-permissions'
import { roleNameOf } from '@/lib/auth/roles'
import { useAppDispatch, useAppSelector } from '@/lib/redux/store'
import { fetchReports } from '@/lib/redux/slices/reportSlice'
import { formatDate } from '@/lib/utils'
import { Report } from '@/types/report'
import { GenerateReportDialog } from './generate-report-dialog'
import { AnalyticsPanel } from './analytics-panel'

export default function ReportsPage() {
  const dispatch = useAppDispatch()
  const { reports, loading, error } = useAppSelector((state) => state.reports)
  const { user } = useAppSelector((state) => state.auth)
  const { canView } = usePermissions()
  const [isModalOpen, setIsModalOpen] = useState(false)

  // The session carries the role's actions; until it does, no request is made
  // for a module this role may not hold.
  const roleReady = Boolean(user && roleNameOf(user))
  const canRead = canView('reports')

  useEffect(() => {
    if (roleReady && canRead) dispatch(fetchReports())
  }, [dispatch, roleReady, canRead])

  if (roleReady && !canRead) {
    return (
      <AppLayout>
        <div className="space-y-10">
          <SectionHeader
            title="Reports & Analytics"
            description="Generate and view organization reports and export audit summaries"
          />
          <AccessDenied area="reports" />
        </div>
      </AppLayout>
    )
  }

  return (
    <AppLayout>
      <div className="space-y-10">
        <SectionHeader
          title="Reports & Analytics"
          description="Generate and view organization reports and export audit summaries"
          action={
            <Button
              onClick={() => setIsModalOpen(true)}
              className="gap-2 brand text-white border edge"
            >
              <Plus size={18} />
              Generate Report
            </Button>
          }
        />

        {error && (
          <div role="alert" className="rounded-2xl border danger-panel p-6 text-sm backdrop-blur-md">
            {error}
          </div>
        )}

        <AnalyticsPanel />

        <div className="panel overflow-hidden">
          {loading && reports.length === 0 ? (
            <div role="status" aria-busy="true">
              <span className="sr-only">Loading reports</span>
              <DataTableSkeleton rows={5} columns={5} />
            </div>
          ) : reports.length === 0 ? (
            <EmptyState
              icon={FileBarChart}
              title="No reports yet"
              description="Reports you generate are kept here with their download links. Generate your first one to start the audit trail."
              action={
                <Button
                  onClick={() => setIsModalOpen(true)}
                  className="gap-2 brand text-white border edge"
                >
                  <Plus size={18} />
                  Generate report
                </Button>
              }
            />
          ) : (
            <DataTable<Report>
              caption="Generated reports"
              columns={[
                {
                  header: 'Report Name',
                  accessor: 'reportName',
                  className: 'font-semibold',
                },
                {
                  header: 'Category',
                  accessor: 'category',
                  render: (cat) => <span className="capitalize">{cat}</span>,
                },
                {
                  header: 'Last Generated',
                  accessor: 'lastGenerated',
                  render: (date) => formatDate(date),
                  className: 'text-foreground/65 text-sm',
                },
                {
                  header: 'Generated By',
                  accessor: 'generatedBy',
                  render: (user) =>
                    typeof user === 'object' && user !== null ? user.name : 'System Admin',
                  className: 'text-foreground/65 text-sm',
                },
                {
                  // An unlabelled header would make the sort control nameless.
                  header: 'Download',
                  accessor: '_id',
                  sortable: false,
                  render: (_id, row) =>
                    row.fileUrl ? (
                      <a
                        href={row.fileUrl}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex h-8 w-8 items-center justify-center rounded-lg text-foreground/65 pointer-coarse:min-h-11 pointer-coarse:min-w-11 transition-colors hover:bg-white/40 hover:text-foreground dark:hover:bg-white/5"
                        aria-label={`Download ${row.reportName}`}
                      >
                        <Download size={16} />
                      </a>
                    ) : (
                      <span
                        className="inline-flex h-8 w-8 items-center justify-center text-foreground/65"
                        aria-hidden="true"
                      >
                        <Download size={16} />
                      </span>
                    ),
                  className: 'text-right',
                },
              ]}
              data={reports}
              renderCard={(report) => (
                <div className="space-y-2">
                  <div className="flex items-start justify-between gap-3">
                    <p className="font-semibold text-foreground">{report.reportName}</p>
                    <Badge className="capitalize">
                      {report.category}
                    </Badge>
                  </div>
                  <p className="text-xs text-foreground/65">
                    {formatDate(report.lastGenerated)} ·{' '}
                    {typeof report.generatedBy === 'object' && report.generatedBy !== null
                      ? report.generatedBy.name
                      : 'System Admin'}
                  </p>
                  {report.fileUrl && (
                    <a
                      href={report.fileUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="inline-flex items-center gap-1.5 text-sm text-brand hover:underline"
                    >
                      <Download size={14} aria-hidden="true" />
                      Download
                    </a>
                  )}
                </div>
              )}
            />
          )}
        </div>
      </div>

      {isModalOpen && <GenerateReportDialog onClose={() => setIsModalOpen(false)} />}
    </AppLayout>
  )
}
